/**
 * run_c_level_shim.mjs — C-level local runtime simulation harness.
 *
 * Runs the UNMODIFIED worker (src/index.mjs) under Node with:
 *  - loader hook: cloudflare:sockets -> tools/sockets-shim.mjs (real node:net TCP)
 *  - shim: WebSocketPair (in-memory, per-request) and Response(101, webSocket)
 *  - real HTTP data server on :8931 serving ./data
 *  - real ws-library server on :8787 bridging native WebSocket clients to the pair
 *  - real TCP echo server on :9077 as proxy destination
 *
 * Then executes test/e2e_local.mjs (same suite as the workerd-based harness)
 * and reports the verdict. Nothing touches any Cloudflare account.
 */
import { register } from 'node:module';
import http from 'node:http';
import net from 'node:net';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawn } from 'node:child_process';
import { WebSocketServer } from 'ws';

register(new URL('./loader.mjs', import.meta.url));
const { installShims } = await import('./worker-shims.mjs');
installShims();

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PORT_DATA = 8931;
const PORT_DEV = 8787;
const PORT_ECHO = 9077;

// env identical to .dev.vars (test-only values, generated by run_c_level.sh)
const env = Object.fromEntries(
  fs.readFileSync(path.join(ROOT, '.dev.vars'), 'utf8')
    .split('\n').filter((l) => l.includes('=') && !l.trim().startsWith('#'))
    .map((l) => [l.slice(0, l.indexOf('=')).trim(), l.slice(l.indexOf('=') + 1).trim()]),
);
env.PROXY_IPS = env.PROXY_IPS || '';

const sessions = [];
const ctx = { waitUntil: (p) => { sessions.push(p); p.catch(() => {}); } };

const worker = (await import(path.join(ROOT, 'src/index.mjs'))).default;

// ---- static data server (what raw.githubusercontent.com provides in production) ----
const dataServer = http.createServer((req, res) => {
  const rel = decodeURIComponent(new URL(req.url, 'http://x').pathname).replace(/^\/+/, '');
  const file = path.join(ROOT, 'data', rel);
  if (!file.startsWith(path.join(ROOT, 'data')) || !fs.existsSync(file) || !fs.statSync(file).isFile()) {
    res.writeHead(404).end('not found');
    return;
  }
  res.writeHead(200, { 'content-type': 'text/plain; charset=utf-8' });
  fs.createReadStream(file).pipe(res);
});
await new Promise((r) => dataServer.listen(PORT_DATA, '127.0.0.1', r));

// NOTE: echo server (9077) is started by the e2e child itself; do not bind here.

// ---- main server: HTTP + WebSocket through worker.fetch ----
const server = http.createServer(async (req, res) => {
  const hmap = {};
  for (let i = 0; i < req.rawHeaders.length; i += 2) hmap[req.rawHeaders[i].toLowerCase()] = req.rawHeaders[i + 1];
  const url = `http://127.0.0.1:${PORT_DEV}${req.url}`;
  const r = new Request(url, { method: req.method, headers: hmap });
  try {
    const out = await worker.fetch(r, env, ctx);
    const body = await out.text();
    res.writeHead(out.status, Object.fromEntries([...out.headers].map(([k, v]) => [k, v])));
    res.end(body);
  } catch (e) {
    res.writeHead(500).end(`harness error: ${e.message}`);
  }
});

const wss = new WebSocketServer({ noServer: true });

server.on('upgrade', async (req, socket, head) => {
  const hmap = {};
  for (let i = 0; i < req.rawHeaders.length; i += 2) hmap[req.rawHeaders[i].toLowerCase()] = req.rawHeaders[i + 1];
  const url = `http://127.0.0.1:${PORT_DEV}${req.url}`;
  const r = new Request(url, { method: 'GET', headers: hmap });
  let out;
  try {
    out = await worker.fetch(r, env, ctx);
  } catch (e) {
    socket.write('HTTP/1.1 500 Internal\r\nConnection: close\r\n\r\n'); socket.destroy(); return;
  }
  if (out.status !== 101 || !out.webSocket) {
    const code = out.status === 403 ? '403 Forbidden' : '404 Not Found';
    socket.write(`HTTP/1.1 ${code}\r\nConnection: close\r\n\r\n`);
    socket.destroy();
    return;
  }
  const clientSide = out.webSocket; // pair[0]
  wss.handleUpgrade(req, socket, head, (wsConn) => {
    wsConn.on('message', (data) => clientSide.send(data));
    clientSide.addEventListener('message', (ev) => { try { wsConn.send(ev.data); } catch {} });
    wsConn.on('close', () => clientSide.close());
    clientSide.addEventListener('close', () => { try { wsConn.close(); } catch {} });
    wsConn.on('error', () => {});
    if (head && head.length) clientSide.send(head);
  });
});

await new Promise((r) => server.listen(PORT_DEV, '127.0.0.1', r));
console.log(`shim runtime up: dev=:${PORT_DEV} data=:${PORT_DATA} echo=:${PORT_ECHO}`);

// ---- run the shared e2e suite against the shim ----
const child = spawn(process.execPath, [path.join(ROOT, 'test/e2e_local.mjs')], {
  stdio: 'inherit',
});
child.on('exit', (code) => {
  // let pending session promises settle briefly before teardown
  setTimeout(() => {
    server.close(); dataServer.close();
    wss.close();
    process.exit(code ?? 1);
  }, 300);
});
