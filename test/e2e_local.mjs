/**
 * e2e_local.mjs — C-level test: full local simulation via `wrangler dev`.
 *
 * NOT part of `npm test` (needs local dev servers). Run:
 *   node test/e2e_local.mjs
 *
 * Prerequisites (started by tools/run_c_level.sh):
 *   - python http.server serving ./data on 127.0.0.1:8931
 *   - wrangler dev on 127.0.0.1:8787 with .dev.vars (test-only values)
 *
 * Covers:
 *   1. GET /              -> 200, no secret leakage
 *   2. GET /sub/<wrong>   -> 404
 *   3. GET /sub/<token>   -> 200, strict base64 vless links, six-region names
 *   4. GET /sub/<token>?region=us -> only US nodes
 *   5. WS on wrong path   -> 403
 *   6. WS bad UUID        -> rejected (close/failure frame)
 *   7. WS valid VLESS     -> [00,00] reply + TCP echo roundtrip via local echo server
 */

import net from 'node:net';
import http from 'node:http';
import assert from 'node:assert/strict';

const BASE = 'http://127.0.0.1:8787';
const DATA_ORIGIN = 'http://127.0.0.1:8931';
const ECHO_PORT = 9077;

// must match .dev.vars generated by tools/run_c_level.sh
import { readFileSync } from 'node:fs';
const devVars = Object.fromEntries(
  readFileSync(new URL('../.dev.vars', import.meta.url), 'utf8')
    .split('\n')
    .filter((l) => l.includes('='))
    .map((l) => [l.slice(0, l.indexOf('=')).trim(), l.slice(l.indexOf('=') + 1).trim()]),
);
const UUID = devVars.VLESS_UUID;
const WS_PATH = devVars.WS_PATH;
const SUB_TOKEN = devVars.SUB_TOKEN;

const results = [];
function record(name, ok, detail = '') {
  results.push({ name, ok, detail });
  console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}${detail ? '  — ' + detail : ''}`);
}

function uuidToBytes(text) {
  const hex = text.replace(/-/g, '');
  return new Uint8Array(16).map((_, i) => parseInt(hex.slice(i * 2, i * 2 + 2), 16));
}

function buildFirstPacket({ uuid = UUID, port = ECHO_PORT, host = '127.0.0.1', payload = '' } = {}) {
  const enc = new TextEncoder();
  const hostBytes = host.split('.').map(Number);
  const pay = enc.encode(payload);
  const pkt = new Uint8Array(1 + 16 + 1 + 1 + 2 + 1 + 4 + pay.length);
  let i = 0;
  pkt[i++] = 0x00;
  pkt.set(uuidToBytes(uuid), i); i += 16;
  pkt[i++] = 0x00; // optlen
  pkt[i++] = 0x01; // TCP
  pkt[i++] = (port >> 8) & 0xff;
  pkt[i++] = port & 0xff;
  pkt[i++] = 0x01; // IPv4
  pkt.set(hostBytes, i); i += 4;
  pkt.set(pay, i);
  return pkt;
}

async function waitWsOpen(ws, timeoutMs = 8000) {
  return new Promise((resolve, reject) => {
    const t = setTimeout(() => reject(new Error('ws open timeout')), timeoutMs);
    ws.addEventListener('open', () => { clearTimeout(t); resolve(); });
    ws.addEventListener('error', (e) => { clearTimeout(t); reject(new Error('ws error')); });
  });
}

async function main() {
  // 0. local TCP echo server as proxy target
  const echo = net.createServer((sock) => sock.on('data', (d) => sock.write(d)));
  await new Promise((r) => echo.listen(ECHO_PORT, '127.0.0.1', r));

  // --- 1. status page ---
  try {
    const r = await fetch(`${BASE}/`);
    const t = await r.text();
    assert.equal(r.status, 200);
    assert.ok(!t.includes(UUID), 'status page leaks UUID');
    assert.ok(!t.toLowerCase().includes('proxy'), 'status page leaks proxy info');
    record('GET / 200 without secrets', true);
  } catch (e) { record('GET / 200 without secrets', false, e.message); }

  // --- 2. wrong subscription token ---
  try {
    const r = await fetch(`${BASE}/sub/definitely-wrong-token`);
    assert.equal(r.status, 404);
    record('GET /sub/<wrong> 404', true);
  } catch (e) { record('GET /sub/<wrong> 404', false, e.message); }

  // --- 3. subscription with token ---
  let allCount = 0;
  try {
    const r = await fetch(`${BASE}/sub/${SUB_TOKEN}`);
    assert.equal(r.status, 200);
    const b64 = await r.text();
    const decoded = Buffer.from(b64, 'base64').toString('utf8');
    const lines = decoded.split('\n').filter(Boolean);
    allCount = lines.length;
    for (const l of lines) {
      assert.match(l, /^vless:\/\/[0-9a-f-]{36}@\d+\.\d+\.\d+\.\d+:443\?/);
      assert.match(l, /security=tls/);
      assert.match(l, /type=ws/);
    }
    const regions = new Set(lines.map((l) => decodeURIComponent(l.split('#')[1]).match(/CF-([A-Z]{2})-/)?.[1]));
    record('GET /sub/<token> base64 vless only', true, `nodes=${lines.length} regions=${[...regions].join(',')}`);
  } catch (e) { record('GET /sub/<token> base64 vless only', false, e.message); }

  // --- 4. region filter ---
  try {
    const r = await fetch(`${BASE}/sub/${SUB_TOKEN}?region=us`);
    const decoded = Buffer.from(await r.text(), 'base64').toString('utf8');
    const lines = decoded.split('\n').filter(Boolean);
    assert.ok(lines.length > 0, 'us filter empty');
    assert.ok(lines.every((l) => decodeURIComponent(l.split('#')[1]).includes('CF-US-')), 'non-US leaked');
    const r2 = await fetch(`${BASE}/sub/${SUB_TOKEN}?region=nl`);
    const d2 = Buffer.from(await r2.text(), 'base64').toString('utf8');
    assert.equal(d2.trim(), '', 'nl (empty region) must yield empty sub, not fabricated');
    record('region filter us/nl', true, `us=${lines.length}, nl empty-as-designed`);
  } catch (e) { record('region filter us/nl', false, e.message); }

  // --- 5. WS wrong path -> 403 (http.request: fetch strips forbidden Upgrade header) ---
  try {
    const status = await new Promise((resolve, reject) => {
      const rq = http.request({
        host: '127.0.0.1', port: 8787, path: '/wrong-path',
        headers: { Connection: 'Upgrade', Upgrade: 'websocket', 'Sec-WebSocket-Version': '13',
                   'Sec-WebSocket-Key': 'x3JJHMbDL1EzLkh9GBhXDw==' },
      });
      rq.on('response', (res) => resolve(res.statusCode));
      rq.on('upgrade', () => reject(new Error('unexpected upgrade on wrong path')));
      rq.on('error', (e) => reject(e));
      rq.end();
    });
    assert.equal(status, 403);
    record('WS wrong path 403', true);
  } catch (e) { record('WS wrong path 403', false, e.message); }

  // --- 6. WS bad UUID rejected ---
  await (async () => {
    let ws;
    try {
      ws = new WebSocket(`ws://127.0.0.1:8787${WS_PATH}`);
      ws.binaryType = 'arraybuffer';
      await waitWsOpen(ws);
      const verdict = await new Promise((resolve) => {
        const t = setTimeout(() => resolve('timeout-no-reject'), 6000);
        ws.addEventListener('message', (ev) => {
          const b = new Uint8Array(ev.data);
          if (b[0] === 0 && b[1] === 0x01) { clearTimeout(t); resolve('failure-frame'); }
        });
        ws.addEventListener('close', (ev) => { clearTimeout(t); resolve(`closed:${ev.code}`); });
        ws.send(buildFirstPacket({ uuid: '00000000-0000-0000-0000-000000000000' }));
      });
      assert.ok(verdict === 'failure-frame' || String(verdict).startsWith('closed:'), `unexpected ${verdict}`);
      record('WS bad UUID rejected', true, String(verdict));
    } catch (e) {
      record('WS bad UUID rejected', false, e.message);
    } finally { try { ws?.close(); } catch {} }
  })();

  // --- 7. valid VLESS -> echo roundtrip ---
  await (async () => {
    let ws;
    try {
      ws = new WebSocket(`ws://127.0.0.1:8787${WS_PATH}`);
      ws.binaryType = 'arraybuffer';
      await waitWsOpen(ws);
      const first = await new Promise((resolve, reject) => {
        const t = setTimeout(() => reject(new Error('no reply frame')), 6000);
        ws.addEventListener('message', (ev) => { clearTimeout(t); resolve(new Uint8Array(ev.data)); });
        ws.send(buildFirstPacket({ payload: 'ping-through-vless' }));
      });
      assert.equal(first.length, 2, 'reply frame must be 2 bytes');
      assert.equal(first[0], 0x00);
      assert.equal(first[1], 0x00, 'answer byte must be success');
      const echoed = await new Promise((resolve, reject) => {
        const t = setTimeout(() => reject(new Error('echo timeout')), 6000);
        ws.addEventListener('message', (ev) => {
          clearTimeout(t);
          resolve(new TextDecoder().decode(ev.data));
        });
      });
      assert.equal(echoed, 'ping-through-vless');
      record('WS valid VLESS echo roundtrip', true, `payload "${echoed}"`);
    } catch (e) {
      record('WS valid VLESS echo roundtrip', false, e.message);
    } finally { try { ws?.close(); } catch {} }
  })();

  echo.close();
  const failed = results.filter((r) => !r.ok);
  console.log(`\nC-level: ${results.length - failed.length}/${results.length} passed`);
  process.exit(failed.length ? 1 : 0);
}

main().catch((e) => { console.error(e); process.exit(1); });
